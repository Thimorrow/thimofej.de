import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const project = resolve(import.meta.dirname, '..');
const design = resolve(process.argv[2] ?? join(project, '../academy-design'));
const experts = resolve(design, '../experts');
const output = join(project, 'src/components/academy/catalog');
const assets = join(project, 'public/projects/academy/catalog');
const entries = ['button', 'page-head', 'sidebar', 'topbar-mission', 'mission-card', 'content-search', 'mission-controls-bar', 'mission-filter-dropdown', 'chat-view', 'step-rail', 'artifact-panel', 'app-frame', 'session-shell'];
const visited = new Set();
const records = [];
const styles = [];
const hash = content => createHash('sha256').update(content).digest('hex');

async function collect(name) {
  if (visited.has(name)) return;
  visited.add(name);
  const path = `base/components/${name}.html`;
  const source = await readFile(join(design, path), 'utf8');
  const header = source.split('\n')[0];
  const quality = header.match(/quality: ([a-z]+)/)?.[1];
  if (quality === 'slop') throw new Error(`Do not import slop catalog unit: ${name}`);
  for (const match of source.matchAll(/<!--\s*include:\s*components\/([\w-]+)\.html\s*-->/g)) await collect(match[1]);
  records.push({ name, path, sha256: hash(source), header, quality });
  const css = [...source.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map(match => match[1]).join('\n');
  if (css) styles.push(`/* ${path} */\n${css}`);
}
for (const name of entries) await collect(name);
const tokenPath = 'apps/web-academy/src/lib/tokens/academy-tokens.css';
const tokenSource = await readFile(join(experts, tokenPath), 'utf8');
// Keep runtime token values intact; Tailwind utility aliases belong to the app build.
const tokens = tokenSource.slice(0, tokenSource.indexOf('\n@theme inline')).replaceAll(':root', '&').replaceAll(/html\[data-theme=(['"])dark\1\]/g, '&[data-theme="dark"]');
const headingSource = await readFile(join(experts, 'apps/web-academy/src/lib/tokens/academy-headings.css'), 'utf8');
const fontSource = await readFile(join(experts, 'apps/web-academy/src/lib/tokens/academy-fonts.css'), 'utf8');
await mkdir(output, { recursive: true });
await mkdir(join(assets, 'fonts'), { recursive: true });
await copyFile(join(project, 'src/components/academy/inter.woff2'), join(assets, 'fonts/inter.woff2'));
for (const font of ['SeasonSans-TRIAL-Bold.woff2', 'SeasonMix-TRIAL-Regular.woff2']) await copyFile(join(experts, 'apps/web-academy/static/fonts', font), join(assets, 'fonts', font));
for (const asset of ['logo-60x60.svg', 'yesterday-academy.svg', 'tomo-face-chat.svg']) await copyFile(join(design, 'base/assets', asset), join(assets, asset));
const css = `/* Generated by scripts/sync-academy-catalog.mjs. Do not hand-edit. */\n@font-face { font-family: Inter; src: url('/projects/academy/catalog/fonts/inter.woff2') format('woff2'); font-weight:100 900; font-style:normal; font-display:swap; }\n${fontSource.replaceAll('/fonts/', '/projects/academy/catalog/fonts/')}\n.academy-modules {\n${tokens}\n${headingSource}\n${styles.join('\n\n').replaceAll(/html\[data-theme=(['"])dark\1\]/g, '&[data-theme="dark"]')}\n}\n`;
await writeFile(join(output, 'catalog.css'), css);
await writeFile(join(output, 'manifest.json'), JSON.stringify({ designRevision: execFileSync('git', ['-C', design, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), units: records, tokens: { path: tokenPath, sha256: hash(tokenSource) }, stylesheetSha256: hash(css), refinements: { 'mission-card': 'Plain 3:2 cover, no tilt or hover lift, compact catalog button.', 'step-rail': 'Unboxed numbered step list and flat progress fill.', 'artifact-panel': 'Continuous document sections; copy action in header.' } }, null, 2) + '\n');
console.log(`Imported ${records.length} Academy catalog modules and their runtime tokens.`);
